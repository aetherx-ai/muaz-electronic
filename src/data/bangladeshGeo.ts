export function getDistrictsByDivision(divisionName: string): BangladeshDistrict[] {
  const div = BANGLADESH_GEO.find((d) => d.name === divisionName);
  return div ? div.districts : [];
}

export function getThanasByDistrict(divisionName: string, districtName: string): string[] {
  const districts = getDistrictsByDivision(divisionName);
  const dist = districts.find((d) => d.name === districtName);
  return dist ? dist.thanas : [];
}
